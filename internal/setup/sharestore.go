package setup

import (
	"fmt"
	"strings"

	"github.com/norlinga/mason/internal/config"
)

// ShareStoreParams configures the share store provisioning script.
type ShareStoreParams struct {
	Share      config.Share
	CaddyUser  string
	Group      string
	Caddyfile  string
	SnippetDir string
	Reload     bool
}

// ShareStoreScript renders the idempotent script that provisions the share store: the
// share tree (objects/ s/ private .mason/) and a Mason-managed vhost that serves links
// while 404ing the private prefixes. It assumes the server bootstrap already ran.
func ShareStoreScript(p ShareStoreParams) (string, error) {
	share := p.Share
	if share.Host == "" || share.URL == "" {
		return "", fmt.Errorf("share URL is required")
	}
	if strings.TrimSpace(share.Path) == "" {
		return "", fmt.Errorf("share path is required")
	}
	user := config.DefaultUser
	if share.Server != nil && share.Server.User != "" {
		user = share.Server.User
	}
	group := orDefault(p.Group, user)
	snippetDir := orDefault(p.SnippetDir, defaultSnippetDir)

	var b strings.Builder
	writeScriptPreamble(&b, "mason share store — "+share.URL, serverHost(share.Server, share.Host))
	fmt.Fprintf(&b, "MASON_USER=%s\n", shellQuote(user))
	fmt.Fprintf(&b, "MASON_GROUP=%s\n", shellQuote(group))
	fmt.Fprintf(&b, "CADDY_USER=%s\n", shellQuote(orDefault(p.CaddyUser, defaultCaddyUser)))
	fmt.Fprintf(&b, "SHARE_ROOT=%s\n", shellQuote(share.Path))
	fmt.Fprintf(&b, "SNIPPET_DIR=%s\n", shellQuote(snippetDir))
	fmt.Fprintf(&b, "CADDYFILE=%s\n\n", shellQuote(orDefault(p.Caddyfile, defaultCaddyfile)))

	b.WriteString("# 1. Share tree (mason owns; objects/s group-readable for Caddy; manifest private)\n")
	b.WriteString("install -d -m 2750 -o \"$MASON_USER\" -g \"$MASON_GROUP\" \"$SHARE_ROOT\" \"$SHARE_ROOT/objects\" \"$SHARE_ROOT/s\"\n")
	b.WriteString("install -d -m 700 -o \"$MASON_USER\" -g \"$MASON_GROUP\" \"$SHARE_ROOT/.mason\"\n\n")

	b.WriteString("# 2. Let Caddy read the share tree (least-privilege via group)\n")
	writeCaddyGroupAccessBlock(&b)
	b.WriteString("\n")

	b.WriteString("# 3. Caddy: Mason-managed share vhost + single import\n")
	writeSnippetInstall(&b, SnippetPath(snippetDir, share.Host), caddyShareSnippet(share.URL, share.Path))
	writeCaddyImportBlock(&b, snippetDir)
	b.WriteString("\n")

	writeCaddyReloadBlock(&b, 4, p.Reload)
	return b.String(), nil
}

// caddyShareSnippet renders the share vhost: serve the root, but hard-404 the private
// prefixes so blobs are reachable only via their symlinks and the manifest is never
// public. Share paths may legitimately be dotfiles, so there is no general dotfile rule.
func caddyShareSnippet(siteAddress, root string) string {
	var b strings.Builder
	b.WriteString(ManagedMarker + "\n")
	fmt.Fprintf(&b, "# %s share store — regenerated by 'mason setup --share'; remove the line above to hand-edit.\n", siteAddress)
	fmt.Fprintf(&b, "%s {\n", siteAddress)
	fmt.Fprintf(&b, "\troot * %s\n", root)
	b.WriteString("\t@mason_private path /objects/* /.mason/*\n")
	b.WriteString("\trespond @mason_private 404\n")
	b.WriteString("\tfile_server\n")
	b.WriteString("}\n")
	return b.String()
}
